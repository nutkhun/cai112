// Embeds the recorded voice clips (assets/voices/<stem>-<alarm|reminder>.m4a, recorded on a Mac
// with mac-countdown/scripts/make-voices.sh) into src/voices.js, so the app can play them
// without loading files. Run: node scripts/embed-voices.mjs
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, '..', 'assets', 'voices');
const types = { '.m4a': 'audio/mp4', '.wav': 'audio/wav', '.mp3': 'audio/mpeg' };
const clips = {};
if (existsSync(dir)) {
  for (const file of readdirSync(dir).sort()) {
    const ext = path.extname(file);
    if (!types[ext]) continue;
    const data = readFileSync(path.join(dir, file)).toString('base64');
    clips[path.basename(file, ext)] = `data:${types[ext]};base64,${data}`;
  }
}
writeFileSync(path.join(here, '..', 'src', 'voices.js'),
  `// Recorded voice clips, generated by scripts/embed-voices.mjs. Do not edit.\nwindow.VOICE_CLIPS = ${JSON.stringify(clips, null, 1)};\n`);
console.log(`Embedded ${Object.keys(clips).length} voice clips into src/voices.js`);
